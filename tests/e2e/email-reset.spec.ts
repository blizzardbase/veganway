import { expect, test } from '@playwright/test';
import { readFile, readdir } from 'node:fs/promises';
import { join } from 'node:path';
import { z } from 'zod';
import AxeBuilder from '@axe-core/playwright';

const mailSchema = z.object({ to: z.string(), link: z.string().url(), text: z.string(), html: z.string() });

test('forgot password email opens a clean reset page and only the new password signs in', async ({ page, baseURL }, testInfo) => {
  const email = `reset.${crypto.randomUUID()}@example.test`;
  const oldPassword = 'old synthetic password';
  const password = 'new synthetic password';
  const origin = new URL(baseURL!).origin;
  const problems: string[] = [];
  page.on('request', (req) => {
    if (new URL(req.url()).origin !== origin) problems.push('Third party request');
    if (req.headers().referer?.includes('token=')) problems.push('Token in referrer');
  });
  const signup = await page.request.post('/api/auth/signup', { headers: { origin }, data: { email, password: oldPassword } });
  expect(signup.status()).toBe(201);
  await page.context().clearCookies();
  await page.goto('/signin');
  await page.getByRole('link', { name: 'Forgot password?', exact: true }).click();
  await expect(page).toHaveURL(/\/forgot-password$/);
  await expect(page.getByRole('heading', { name: 'Forgot password?', exact: true })).toBeVisible();
  await page.getByLabel('Email', { exact: true }).fill(email);
  await page.getByRole('button', { name: 'Send reset link', exact: true }).click();
  await expect(page.getByRole('status').filter({ hasText: 'If an account uses this email' })).toBeVisible({ timeout: 10_000 });
  const directory = process.env.VW_E2E_MAIL_DIR;
  if (!directory) throw new Error('Missing isolated mail directory');
  const mails = await Promise.all((await readdir(directory)).filter((file) => file.endsWith('.json')).map(async (file) => mailSchema.parse(JSON.parse(await readFile(join(directory, file), 'utf8')))));
  const mail = mails.find((item) => item.to === email);
  expect(mail).toBeDefined();
  if (!mail) throw new Error('Reset email not recorded');
  expect(mail.text).toContain('It works for 30 minutes.');
  expect(mail.html).not.toMatch(/<img|tracking/i);
  const response = await page.goto(mail.link);
  expect(response?.headers()['referrer-policy']).toBe('no-referrer');
  await expect(page).toHaveURL(/\/reset$/);
  await expect(page.getByLabel('New password', { exact: true })).toBeVisible();
  await expect(page.getByText(/recovery code/i)).toHaveCount(0);
  await page.getByLabel('New password', { exact: true }).fill(password);
  await page.getByLabel('Repeat new password', { exact: true }).fill('a different password');
  await page.getByRole('button', { name: 'Reset password', exact: true }).click();
  await expect(page.getByRole('alert')).toHaveText('The passwords do not match.');
  await page.getByLabel('Repeat new password', { exact: true }).fill(password);
  const accessibility = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa', 'wcag22aa']).analyze();
  expect(accessibility.violations).toEqual([]);
  expect(await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth)).toBeLessThanOrEqual(0);
  await page.screenshot({ path: testInfo.outputPath('reset.png'), fullPage: true });
  await page.getByRole('button', { name: 'Reset password', exact: true }).click();
  await expect(page.getByRole('status').filter({ hasText: 'Password changed. Sign in with your new password.' })).toBeVisible();
  await page.getByLabel('Email', { exact: true }).fill(email);
  await page.getByLabel('Password', { exact: true }).fill(oldPassword);
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page.getByRole('alert')).toHaveText('Email or password is wrong.');
  await page.getByLabel('Password', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page).toHaveURL(/\/$/);
  await page.goto(mail.link);
  await page.getByLabel('New password', { exact: true }).fill(password);
  await page.getByLabel('Repeat new password', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Reset password', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('invalid or has expired');
  await expect(page.getByRole('link', { name: 'Request a new link', exact: true })).toBeVisible();
  expect(problems).toEqual([]);
});
